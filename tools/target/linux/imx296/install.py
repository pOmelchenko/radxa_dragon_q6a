#!/usr/bin/env python3
"""Install a separate Radxa OS boot entry for an InnoMaker IMX296 on CAM2."""
import argparse
import hashlib
import os
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "q6a-cam2-innomaker-imx296.dts"
ESP = Path("/boot/efi")
MARKER = "# Generated by q6a imx296/install.py"
TITLE = "InnoMaker IMX296 Mono on CAM2"


def output(*args):
    return subprocess.check_output(args, text=True).strip()


def efi_file(esp, name):
    path = PurePosixPath(name)
    if path.root != "/" or ".." in path.parts or "\\" in name:
        raise ValueError(f"Недопустимый путь EFI: {name}")
    target = esp.joinpath(*path.parts[1:])
    if not target.resolve().is_relative_to(esp.resolve()):
        raise ValueError(f"Путь вне EFI: {name}")
    return target


def dependencies():
    packages = {"device-tree-compiler": ("dtc", "fdtoverlay", "fdtget"),
                "v4l-utils": ("media-ctl", "v4l2-ctl"), "kmod": ("modinfo", "modprobe")}
    missing = [pkg for pkg, cmds in packages.items() if not all(shutil.which(c) for c in cmds)]
    if missing:
        subprocess.run(["apt-get", "install", "-y", "--no-remove", "--no-install-recommends",
                        *missing], check=True)


def fields(lines, key):
    return [line.split()[1:] for line in lines if line.split()[:1] == [key]]


def single_path(lines, key):
    rows = fields(lines, key)
    if len(rows) != 1 or len(rows[0]) != 1:
        raise ValueError(f"В записи загрузки ожидается один путь {key}.")
    return rows[0][0]


def atomic_write(path, data):
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".imx296-", delete=False) as f:
        tmp = Path(f.name)
        try:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        except BaseException:
            tmp.unlink(missing_ok=True)
            raise
    try:
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def install(esp, entry, kernel, work):
    entries = esp / "loader/entries"
    if entry.parent != entries or entry.suffix != ".conf" or entry.is_symlink():
        raise ValueError(f"Выберите исходную .conf из {entries}.")
    lines = entry.read_text().splitlines()
    if MARKER in lines or len(fields(lines, "title")) != 1:
        raise ValueError("Выберите исходную загрузочную запись Radxa OS с полем title.")
    base_path = single_path(lines, "devicetree")
    linux_path = single_path(lines, "linux")
    for name in (linux_path, base_path):
        if kernel not in PurePosixPath(name).parts or not efi_file(esp, name).is_file():
            raise ValueError(f"Запись должна ссылаться на файлы работающего ядра {kernel}: {name}")
    base = efi_file(esp, base_path)
    if "radxa,dragon-q6a" not in output("fdtget", base, "/", "compatible").split():
        raise ValueError(f"Выбран DTB другой платы: {base}")
    overlays = [p for row in fields(lines, "devicetree-overlay") for p in row]
    current = base
    if overlays:
        current = work / "current.dtb"
        subprocess.run(["fdtoverlay", "-i", base, "-o", current,
                        *(efi_file(esp, p) for p in overlays)], check=True)

    bus = output("fdtget", current, "/__symbols__", "cci1_i2c0")
    phy = output("fdtget", current, "/__symbols__", "camss") + "/ports/port@2"
    sensors = output("fdtget", "-l", current, bus).split()
    endpoints = output("fdtget", "-l", current, phy).split()
    if any(s.endswith("@1a") for s in sensors) or any(n.split("@")[0] == "endpoint" for n in endpoints):
        raise ValueError("В исходной записи уже настроена камера на CAM2. Выберите запись со свободным J16.")

    overlay = work / "camera.dtbo"
    subprocess.run(["dtc", "-@", "-I", "dts", "-O", "dtb", "-o", overlay, SOURCE], check=True)
    merged = work / "camera.dtb"
    subprocess.run(["fdtoverlay", "-i", current, "-o", merged, overlay], check=True)
    sensor = bus + "/camera@1a"
    tx, rx = sensor + "/port/endpoint", phy + "/endpoint"
    if (output("fdtget", merged, sensor, "compatible") != "sony,imx296"
            or output("fdtget", merged, rx, "remote-endpoint") != output("fdtget", merged, tx, "phandle")
            or output("fdtget", merged, tx, "remote-endpoint") != output("fdtget", merged, rx, "phandle")):
        raise ValueError("Проверка связи IMX296 с CSIPHY2 не прошла.")

    # Publish a validated DTB before its entry. Older trial entries stay bootable
    # across interrupted installs because an existing DTB is never overwritten.
    blob = merged.read_bytes()
    digest = hashlib.sha256(blob).hexdigest()[:16]
    dtb = base.with_name(f"imx296-cam2-{digest}.dtb")
    target = entries / f"imx296-cam2-{entry.stem}.conf"
    if target.exists() and MARKER not in target.read_text().splitlines():
        raise ValueError(f"Файл принадлежит другой конфигурации: {target}")
    new_lines = [MARKER]
    for line in lines:
        key = line.split()[:1]
        if key == ["title"]:
            line = f"title {TITLE} ({entry.stem})"
        elif key == ["devicetree"]:
            line = f"devicetree /{dtb.relative_to(esp).as_posix()}"
        elif key == ["devicetree-overlay"]:
            continue  # Already merged in the original order.
        new_lines.append(line)
    config = ("\n".join(new_lines) + "\n").encode()
    if dtb.exists():
        if dtb.read_bytes() != blob:
            raise ValueError(f"Содержимое {dtb} отличается от ожидаемого.")
    else:
        atomic_write(dtb, blob)
    if not target.exists() or target.read_bytes() != config:
        atomic_write(target, config)
    return target


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--entry", type=Path, help="исходная запись из /boot/efi/loader/entries")
    args = parser.parse_args()
    if sys.platform != "linux" or os.geteuid() != 0:
        parser.exit(1, "Запустите на Q6A: sudo python3 install.py\n")
    if b"radxa,dragon-q6a" not in Path("/proc/device-tree/compatible").read_bytes().split(b"\0"):
        raise ValueError("Ожидается плата Radxa Dragon Q6A.")
    if not ESP.is_mount():
        raise ValueError("Сначала смонтируйте EFI System Partition в /boot/efi.")
    kernel = os.uname().release
    entry = args.entry or ESP / f"loader/entries/RadxaOS-{kernel}.conf"
    if not entry.is_file():
        raise ValueError(f"Нет {entry}. Укажите исходную запись текущего ядра через --entry.")
    dependencies()
    for module in ("imx296", "qcom_camss", "i2c-qcom-cci"):
        subprocess.run(["modinfo", "-k", kernel, "-F", "filename", module], check=True)

    import fcntl  # Linux target only.

    with open("/run/lock/q6a-imx296-cam2.lock", "a") as lock, tempfile.TemporaryDirectory() as work:
        fcntl.flock(lock, fcntl.LOCK_EX)
        target = install(ESP, entry, kernel, Path(work))
    print(f"Установлено: {target}\nВыберите в embloader: {TITLE} ({entry.stem})")
    print(f"Исходная запись для возврата: {entry.name}")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
