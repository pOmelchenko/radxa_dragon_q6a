#!/usr/bin/env python3
"""Install a Waveshare 35H trial boot entry on a Radxa Dragon Q6A."""
import argparse
import os
from pathlib import Path, PurePosixPath
import platform
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
OVERLAY = "q6a-waveshare-35h.dtbo"
MODULE = "panel-waveshare-35h.ko"
TITLE = "Waveshare 35H (auto)"
PULSE_TITLE = "Waveshare 35H (sync-pulse)"
PULSE_ARG = "panel_waveshare_35h.sync_pulse=1"
MARKER = "# Generated by waveshare-35h/install.py"
BOARD = "qcs6490-radxa-dragon-q6a"
OLD_DISPLAYS = {
    "q6a-btt-tft50-display.dtbo",
    "q6a-btt-tft50-power.dtbo",
    f"{BOARD}-raspberry-pi-7-inch-touchscreen.dtbo",
    f"{BOARD}-raspberry-pi-7-inch-touchscreen-2.dtbo",
    f"{BOARD}-radxa-display-8hd.dtbo",
    f"{BOARD}-radxa-display-8hd-2lane.dtbo",
    f"{BOARD}-radxa-display-10fhd.dtbo",
}


def output(*args):
    return subprocess.check_output(args, text=True).strip()


def dependencies(kernel, headers, build):
    packages = []
    for package, commands in (
        ("device-tree-compiler", ["dtc", "fdtoverlay", "fdtget"]),
        ("kmod", ["modinfo", "depmod"]),
    ):
        if any(shutil.which(cmd) is None for cmd in commands):
            packages.append(package)
    if build:
        if not all(shutil.which(cmd) for cmd in ("make", "gcc", "ld")):
            packages.append("build-essential")
        if not (headers / "Makefile").is_file():
            packages.append(f"linux-headers-{kernel}")
    if packages:
        subprocess.run(["apt-get", "install", "-y", "--no-remove",
                        "--no-install-recommends", *packages], check=True)


def build_files(headers, work):
    for name in ("Kbuild", "panel-waveshare-35h.c"):
        shutil.copyfile(HERE / name, work / name)
    subprocess.run(["make", "-C", headers, f"M={work}", "modules"], check=True)
    subprocess.run(["dtc", "-@", "-I", "dts", "-O", "dtb", "-o", work / OVERLAY,
                    HERE / "q6a-waveshare-35h.dts"], check=True)
    return work / MODULE, work / OVERLAY


def efi_file(esp, name):
    path = PurePosixPath(name)
    if path.root != "/" or ".." in path.parts or "\\" in name:
        raise ValueError(f"Invalid EFI path: {name}")
    target = esp.joinpath(*path.parts[1:])
    if not target.resolve().is_relative_to(esp.resolve()):
        raise ValueError(f"Path is outside the EFI partition: {name}")
    return target


def trial_entry(original, kernel, sync_pulse=False):
    lines = original.splitlines(keepends=True)
    if MARKER in original.splitlines():
        raise ValueError("Select an original boot entry as the source")
    fields = {}
    for i, line in enumerate(lines):
        words = line.split()
        if words:
            fields.setdefault(words[0], []).append((i, words[1:]))

    paths = {}
    for key in ("linux", "devicetree"):
        rows = fields.get(key, [])
        if len(rows) != 1 or len(rows[0][1]) != 1:
            raise ValueError(f"Expected one {key} path in the boot entry")
        paths[key] = rows[0][1][0]
        if kernel not in PurePosixPath(paths[key]).parts:
            raise ValueError(f"{key} path does not reference the running kernel: {paths[key]}")

    titles = fields.get("title", [])
    if len(titles) != 1:
        raise ValueError("Expected one title in the boot entry")
    lines[titles[0][0]] = f"title {PULSE_TITLE if sync_pulse else TITLE}\n"

    if sync_pulse:
        # Put the module parameter before a possible '--' for userspace.
        options = fields.get("options", [])
        if options:
            i, words = options[0]
            if len(options) != 1 or any(w.replace("-", "_").startswith(
                    "panel_waveshare_35h.sync_pulse=") for w in words):
                raise ValueError("Ambiguous options for the sync-pulse trial")
            previous = lines[i].strip()[len("options"):].lstrip()
            lines[i] = f"options {PULSE_ARG} {previous}".rstrip() + "\n"
        else:
            lines.append(f"\noptions {PULSE_ARG}\n")

    new_path = str(PurePosixPath(paths["devicetree"]).parent / "dtbo" / OVERLAY)
    kept, removed = [], []
    for i, overlays in fields.get("devicetree-overlay", []):
        lines[i] = ""
        for path in overlays:
            if PurePosixPath(path).name in OLD_DISPLAYS:
                removed.append(path)
            elif path != new_path:
                kept.append(path)
    text = "".join(lines).rstrip("\r\n")
    text += "\n" + MARKER + "\ndevicetree-overlay " + " ".join([*kept, new_path]) + "\n"
    return text, paths, new_path, kept, removed


def atomic_write(target, data, mode):
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(dir=target.parent, prefix=".ws35h-")
    temp = Path(name)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            if mode is not None:  # The ESP uses mount-wide permissions on FAT.
                os.chmod(temp, mode)
            os.fsync(f.fileno())
        os.replace(temp, target)
    finally:
        temp.unlink(missing_ok=True)


def publish(module, overlay, entry, payloads, kernel):
    targets = (module, overlay, entry)
    previous = {}
    for target in targets:
        if target.is_symlink():
            raise ValueError(f"Unexpected symlink: {target}")
        previous[target] = target.read_bytes() if target.exists() else None

    if (previous[entry] is not None and previous[entry] != payloads[2]
            and MARKER.encode() not in previous[entry].splitlines()):
        raise ValueError(f"Boot entry already exists; move it aside to keep it: {entry}")

    changed = []
    try:
        for target, data in zip(targets, payloads):
            if previous[target] != data:
                atomic_write(target, data, 0o644 if target == module else None)
                changed.append(target)
            if target == module:
                subprocess.run(["depmod", "-a", kernel], check=True)
                selected = Path(output("modinfo", "-k", kernel, "-n", MODULE[:-3]))
                if selected.resolve() != module.resolve():
                    raise ValueError(f"A different panel module is selected: {selected}")
    except (OSError, ValueError, subprocess.CalledProcessError, KeyboardInterrupt):
        for target in reversed(changed):
            if previous[target] is None:
                target.unlink()
            else:
                atomic_write(target, previous[target], 0o644 if target == module else None)
        if module in changed:
            subprocess.run(["depmod", "-a", kernel], check=True)
        raise


def install(esp, source, module_root, kernel, work, module, overlay, sync_pulse=False):
    profile = "pulse" if sync_pulse else "auto"
    target = esp / "loader/entries" / f"waveshare-35h-{profile}-{kernel}.conf"
    if source.resolve().parent != target.parent.resolve() or source.resolve() == target.resolve():
        raise ValueError(f"Select an original entry in {target.parent}")
    original = source.read_bytes()
    text, paths, overlay_path, kept, removed = trial_entry(original.decode(), kernel, sync_pulse)
    if not efi_file(esp, paths["linux"]).is_file():
        raise ValueError(f"Kernel image is missing: {paths['linux']}")
    dtb = efi_file(esp, paths["devicetree"])
    if "radxa,dragon-q6a" not in output("fdtget", dtb, "/", "compatible").split():
        raise ValueError(f"Base DTB is for another board: {dtb}")

    if output("modinfo", "-F", "vermagic", module).split()[:1] != [kernel]:
        raise ValueError(f"Module does not match {kernel}: {module}")
    alias = "of:N*T*Cwaveshare,35h-dsi"
    if alias not in output("modinfo", "-F", "alias", module).splitlines():
        raise ValueError(f"Module has no Waveshare 35H alias: {module}")
    if "sync_pulse:bool" not in output("modinfo", "-F", "parmtype", module).splitlines():
        raise ValueError(f"Update the panel module to the version with sync_pulse support: {module}")

    other_files = [efi_file(esp, name) for name in kept]
    for other in other_files:
        resources = output("fdtget", "-d", "", "-t", "s", other, "/metadata", "exclusive").split()
        if {"mdss_dsi", "gpio80"}.intersection(resources):
            raise ValueError(f"Another overlay uses DSI or GPIO80: {other}")
    merged = work / "merged.dtb"
    subprocess.run(["fdtoverlay", "-i", dtb, "-o", merged, *other_files, overlay], check=True)
    host = output("fdtget", merged, "/__symbols__", "mdss_dsi")
    if output("fdtget", merged, f"{host}/panel@0", "compatible") != "waveshare,35h-dsi":
        raise ValueError("Merged DTB is missing the 35H panel")
    touch_bus = output("fdtget", merged, "/__symbols__", "i2c13")
    touch = f"{touch_bus}/touchscreen@5d"
    if (output("fdtget", merged, touch, "compatible") != "goodix,gt911"
            or output("fdtget", "-t", "x", merged, touch, "reg") != "5d"):
        raise ValueError("Merged DTB is missing the GT911 at address 0x5d")

    if source.read_bytes() != original:
        raise ValueError(f"Boot entry changed during installation; retry: {source}")
    for name in removed:
        print(f"Omitting from the trial entry: {name}")
    publish(module_root / "updates" / MODULE, efi_file(esp, overlay_path), target,
            (module.read_bytes(), overlay.read_bytes(), text.encode()), kernel)
    title = PULSE_TITLE if sync_pulse else TITLE
    print(f"Installed {target}. Select '{title}' in embloader. Original entry: {source.name}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prebuilt", type=Path, metavar="DIR",
                        help="use artifacts/waveshare-35h from the unpacked binary archive")
    parser.add_argument("--entry", type=Path, help="source EFI boot entry for the running kernel")
    parser.add_argument("--sync-pulse", action="store_true",
                        help="create a separate trial using DSI sync pulses and HSync end packets")
    args = parser.parse_args()
    if sys.platform != "linux" or os.geteuid() != 0:
        parser.exit(1, "Run on the Q6A with sudo python3 install.py\n")

    import fcntl  # Linux only.
    kernel = platform.release()
    esp = Path("/boot/efi")
    module_root = Path("/lib/modules") / kernel
    board = Path("/sys/firmware/devicetree/base/compatible").read_bytes().split(b"\0")
    if b"radxa,dragon-q6a" not in board or not esp.is_mount():
        raise ValueError("Expected a Radxa Dragon Q6A with the EFI partition mounted at /boot/efi")
    source = args.entry
    if source is None:
        token_file = Path("/etc/kernel/entry-token")
        token = token_file.read_text().strip() if token_file.is_file() else "RadxaOS"
        source = esp / "loader/entries" / f"{token}-{kernel}.conf"
    if not source.is_file():
        raise ValueError(f"Source entry missing: {source}. Select the current-kernel entry with --entry")
    print(f"Preparing trial from {source}", flush=True)
    with Path("/run/lock/waveshare-35h.lock").open("a") as lock, tempfile.TemporaryDirectory() as tmp:
        fcntl.flock(lock, fcntl.LOCK_EX)
        work = Path(tmp)
        dependencies(kernel, module_root / "build", args.prebuilt is None)
        if args.prebuilt is None:
            module, overlay = build_files(module_root / "build", work)
        else:
            module, overlay = args.prebuilt / kernel / MODULE, args.prebuilt / OVERLAY
        install(esp, source, module_root, kernel, work, module, overlay, args.sync_pulse)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        sys.exit(f"Installation failed: {error}")
